class Restaurant {
  final String name;
  final String imagePath;
  final String time;
  final String category;
  final double rating;
  final int reviews;
  final String address;

  Restaurant({
    required this.name,
    required this.imagePath,
    required this.time,
    required this.category,
    required this.rating,
    required this.reviews,
    required this.address,
  });
}
